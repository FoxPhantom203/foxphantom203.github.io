/**
 * Debounce function to limit rapid function calls
 */
function debounce(func, wait = 300) {
  let timeout;
  return function executedFunction(...args) {
    const later = () => {
      clearTimeout(timeout);
      func(...args);
    };
    clearTimeout(timeout);
    timeout = setTimeout(later, wait);
  };
}

/**
 * Format code with syntax highlighting
 */
function formatCode(code, language = 'javascript') {
  const languages = {
    javascript: { keyword: '#ff6b35', string: '#fbbf24', comment: '#9a9aad' },
    python: { keyword: '#3776ab', string: '#2a7f62', comment: '#6a7a8a' },
    html: { tag: '#e34c26', attribute: '#ff6b35', value: '#fbbf24' }
  };
  
  const colors = languages[language] || languages.javascript;
  
  // Simple syntax highlighting (in a real app, use a proper library)
  return code
    .replace(/\b(function|const|let|var|return|if|else|for|while)\b/g, 
      `<span style="color:${colors.keyword}">$1</span>`)
    .replace(/(\/\/.*$|\/\*[\s\S]*?\*\/)/gm, 
      `<span style="color:${colors.comment}">$1</span>`)
    .replace(/("[^"]*"|'[^']*')/g, 
      `<span style="color:${colors.string}">$1</span>`);
}

